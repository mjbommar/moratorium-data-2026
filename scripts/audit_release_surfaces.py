#!/usr/bin/env python3
"""Inventory release consumer surfaces without accepting claims or editing consumers."""
import argparse
import datetime as dt
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
REPOSITORIES = ['moratorium-data-2026', 'moratorium-paper', 'datacenter-paper-2026',
                'datacenter-data-integration', 'servercountry.org',
                'fightadatacenter.com', 'datacenter-2026-book']
SUFFIXES = {'.md', '.tex', '.html', '.astro', '.tsx', '.cff'}
PATTERNS = {
    'inventory_totals': r'\b(?:1,?291|1,?293|1,?063|1,?071|440|442)\b',
    'ballot_totals': r'\b(?:29|44|45|46|47|48|49)\s+(?:reviewed\s+)?(?:ballot|measure|result)',
    'freshness_or_completeness': r'\b(?:currently|latest|up.to.date|comprehensive|complete coverage|all jurisdictions|as of)\b',
    'release_or_cutoff': r'\b(?:release|September 23|November [356]|2026-09-23|2026-11-0[356])\b',
    'interpretation': r'\b(?:moratori\w*|ballot|referend\w*|certif\w*|data.center\w*|ban|prohibit\w*)\b',
    'percentages': r'\b\d+(?:\.\d+)?\s*(?:%|percent\b)',
}
REGEXES = {key: re.compile(value, re.I) for key, value in PATTERNS.items()}


def git(directory, *args):
    result = subprocess.run(['git', '-C', str(directory), *args], capture_output=True, check=True)
    return result.stdout


def inventory():
    repositories = []
    for name in REPOSITORIES:
        directory = ROOT if name == ROOT.name else ROOT.parent / name
        if not directory.is_dir():
            repositories.append({'repository': name, 'state': 'missing_checkout', 'surfaces': []})
            continue
        paths = git(directory, 'ls-files', '-z').decode().split('\0')
        surfaces = []
        for relative in sorted(filter(None, paths)):
            path = directory / relative
            if path.suffix.lower() not in SUFFIXES and relative not in {'data/summary_stats.json', 'package.json'}:
                continue
            # Retained research and immutable snapshots are audit inputs, not current copy.
            if relative.startswith(('work/', 'data/expanded-snapshots/', 'node_modules/', '.venv/')):
                continue
            if not path.is_file():
                continue
            raw = path.read_bytes()
            try:
                text = raw.decode('utf-8')
            except UnicodeDecodeError:
                continue
            hits = []
            categories = set()
            match_counts = {key: 0 for key in REGEXES}
            for number, line in enumerate(text.splitlines(), 1):
                found = [key for key, regex in REGEXES.items() if regex.search(line)]
                categories.update(found)
                for key in found:
                    match_counts[key] += 1
                if found and len(hits) < 8:
                    hits.append({'line': number, 'categories': found})
            generated = ('Generated by ' in text[:1000] or relative.startswith(('site/', 'states/')))
            historical_candidate = relative.startswith(('collaborators/', 'releases/', 'archive/', 'archives/')) or path.name.upper().startswith('CHANGELOG')
            surfaces.append({'path': relative, 'sha256': hashlib.sha256(raw).hexdigest(),
                             'bytes': len(raw), 'categories': sorted(categories),
                             'matched_line_counts': {key: value for key, value in match_counts.items() if value},
                             'sample_matches': hits,
                             'kind_hint': 'historical_candidate' if historical_candidate else 'generated_candidate' if generated else 'manual_or_unclassified',
                             'review_disposition': 'requires_review',
                             'required_action': 'Verify source/cohort and current-versus-historical role before updating or retaining; hint is not an approved disposition.'})
        status = git(directory, 'status', '--porcelain')
        repositories.append({'repository': name, 'state': 'inspected_checkout',
                             'head': git(directory, 'rev-parse', 'HEAD').decode().strip(),
                             'worktree_changed_entries': len(status.splitlines()),
                             'worktree_status_sha256': hashlib.sha256(status).hexdigest(),
                             'surfaces': surfaces})
    return {'schema_version': '1.0.0', 'observed_at': dt.datetime.now(dt.timezone.utc).isoformat(),
            'collector_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'scope': 'Read-only tracked UTF-8 prose/template/selected metadata inventory of seven named checkouts. Pattern matches are leads, not accepted claims or completed review. Excludes research/raw archives and immutable expanded generations. Remote refs/deployments and unlisted author sites are not inspected.',
            'patterns': PATTERNS, 'repositories': repositories,
            'unresolved_scope': ['Identify author-site references and any additional consumer repositories.',
                                 'Inspect PDF/chart/image artifacts and rendered/deployed outputs separately.',
                                 'Assign authoritative source/view, reviewer and final disposition per manual claim.',
                                 'Determine dated historical editions explicitly; path hints do not approve retention.']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    result = inventory()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + '\n')
    for repo in result['repositories']:
        surfaces = repo['surfaces']
        print(repo['repository'], len(surfaces), 'surfaces;',
              sum(bool(row['categories']) for row in surfaces), 'with candidate claims;', repo['state'])


if __name__ == '__main__':
    main()
