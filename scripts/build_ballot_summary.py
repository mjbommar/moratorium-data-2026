#!/usr/bin/env python3
"""Build a dated public view of reviewed current result observations, not a census."""
import argparse
from pathlib import Path

from check_expanded_publication import check
from expanded_data import validate, certified_result_count
from expanded_promotion import ROOT, require


def cell(value):
    if value is None:
        return 'unknown'
    return str(value).replace('|',r'\|').replace('\n',' ')


def citation(source):
    return source.get('citation_url') or source['url']


def render(rows, snapshot):
    results=list(rows['measure_results'].values())
    superseded={r['supersedes_id'] for r in results if r['supersedes_id']}
    live=[r for r in results if r['result_observation_id'] not in superseded]
    lines=['<!-- Generated by scripts/build_ballot_summary.py; do not edit by hand. -->',
           '# Reviewed ballot results','',
           f"**{len(rows['ballot_measures'])} reviewed measure records · {len(live)} current result observations · "
           f"{certified_result_count(rows)} current certified observations.**",'',
           'This is a reviewed subset, not a complete election census. Each row is one current result observation; '
           'multiple observations for a measure remain separate. Unknown categories are not zero.','',
           'Reporting scope distinguishes whole-jurisdiction observations from named parts. '
           'Missing legacy scope is not assumed to cover the whole electorate; observations are not summed.','',
           'Yes-vote direction follows the question wording. Advisory results express voter sentiment; '
           'they do not by themselves enact a restriction or authorize a project.','',
           '| Measure | Election | Reporting scope | Bindingness | Yes-vote direction | Yes | No | Blank | Ballots cast | Certification | Reported outcome |',
           '|---|---|---|---|---|---:|---:|---:|---:|---|---|']
    def order(result):
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        return jurisdiction['state'],jurisdiction['name'],result['observed_at'],result['result_observation_id']
    for result in sorted(live,key=order):
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        election=rows['elections'][measure['election_id']]
        source=rows['source_documents'][result['source_document_id']]
        title=jurisdiction['name']+', '+jurisdiction['state']+' — '+(measure['designation'] or measure['title'] or 'undesignated')
        label=f"[{title}](<{citation(source)}>)"
        date=election['election_date']['earliest'] if election['election_date']['precision']=='day' else (election['election_date']['original_text'] or 'unknown')
        cert=result['certification_status']+((' '+result['certification_date']) if result['certification_date'] else '')
        scope=result.get('reporting_scope')
        scope_label=({'jurisdiction_total':'Whole jurisdiction', 'jurisdiction_part':'Partial jurisdiction',
                      'unknown':'Unknown scope'}[scope['kind']]+': '+scope['description']) if scope else 'scope not recorded'
        values=[label,date,scope_label,measure['bindingness'],measure['yes_direction'].replace('_',' '),result['yes_votes'],result['no_votes'],result.get('blank_votes'),result['ballots_cast'],cert,result['reported_outcome']]
        lines.append('| '+' | '.join(cell(v) for v in values)+' |')
    source_notes=[]
    for result in sorted(live,key=order):
        categories=result.get('source_vote_categories',[])
        totals=result.get('source_vote_totals',[])
        if not categories and not totals:continue
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        source=rows['source_documents'][result['source_document_id']]
        notes=[cell(x['label'])+': '+str(x['count'])+' (unmapped category)' for x in categories]
        notes += [cell(x['label'])+': '+str(x['count'])+' ('+cell(x['scope'])+')' for x in totals]
        title=jurisdiction['name']+', '+jurisdiction['state']+' — '+(measure['designation'] or measure['title'] or 'undesignated')
        source_notes.append('- ['+cell(title)+'](<'+citation(source)+'>): '+'; '.join(notes)+'.')
    if source_notes:
        lines += ['', 'Additional source labels and totals remain separate from blanks, valid votes and ballots cast.']+source_notes
    accounting_notes=[]
    for result in sorted(live,key=order):
        for claim in sorted(rows['claims'].values(),key=lambda c:c['claim_id']):
            if (claim['subject']!={'table':'measure_results','id':result['result_observation_id']}
                    or claim['predicate']!='derived_accounting_discrepancy'):
                continue
            value=claim['value']
            if not isinstance(value,dict) or not {'unreconciled_ballots','formula','classification'} <= set(value):
                continue
            measure=rows['ballot_measures'][result['measure_id']]
            jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
            source=rows['source_documents'][claim['source_document_id']]
            title=jurisdiction['name']+', '+jurisdiction['state']+' — '+(measure['designation'] or measure['title'] or 'undesignated')
            accounting_notes.append('- ['+cell(title)+'](<'+citation(source)+'>): source accounting difference '+
                                    cell(value['unreconciled_ballots'])+'; '+cell(value['formula'])+'. '+
                                    cell(value['classification'])+'.')
    if accounting_notes:
        lines += ['', 'Reviewed accounting discrepancies below retain source values without filling unknown vote categories.']+accounting_notes
    no_results=set(rows['ballot_measures'])-{r['measure_id'] for r in live}
    if no_results:
        lines += ['',f'{len(no_results)} reviewed measures have no current result observation; absence is not a defeated or unqualified measure.']
    lines += ['', 'Reported outcomes and certification are separate from calculated passage rules, operative dates and legal force. '
              'A reported approval does not automatically add an in-force legacy moratorium. '
              'See [scope and interpretation](ballot-measures.md) for unresolved legal implementation.','',
              f'{len(results)} result observations are retained, including explicitly superseded history. '
              'This view excludes superseded observations without deleting them.','',
              '## Sources for reported outcomes','']
    for result in sorted(live,key=order):
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        sources={citation(rows['source_documents'][rows['claims'][cid]['source_document_id']])
                 for cid in result.get('value_methods',{}).get('reported_outcome',{}).get('claim_ids',[])}
        if sources:
            lines.append('- '+cell(jurisdiction['name'])+': '+', '.join('[reported-outcome source](<'+url+'>)' for url in sorted(sources))+'.')
    lines += ['',f'Pinned canonical snapshot: `{snapshot}`. Source observation times remain in the JSONL records; '
              'this generation is not a renewed current-force check.','',
              f'[Canonical publication protocol](expanded-promotion.md) · [Raw reviewed tables](../data/expanded-snapshots/{snapshot}/ballot_measures.jsonl)','']
    return '\n'.join(lines)


def build(directory, registry):
    checked=check(directory,registry,ROOT/'data/moratorium_inventory.csv',ROOT/'data/state_legislation.csv')
    pinned=directory.resolve(strict=True)
    require(pinned.name==checked['snapshot_sha256'],'Publication changed during summary build; rerun against one generation')
    errors,rows=validate(pinned,ROOT/'data/moratorium_inventory.csv',ROOT/'data/state_legislation.csv')
    require(not errors,'Invalid published data: '+'; '.join(errors))
    return render(rows,pinned.name)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output',type=Path,default=ROOT/'docs/ballot-results.md')
    args=parser.parse_args();text=build(ROOT/'data/expanded',ROOT/'data/identities/expanded.jsonl')
    if args.check:
        require(args.output.exists() and args.output.read_text()==text,'Ballot summary is stale; run scripts/build_ballot_summary.py')
        print('Reviewed ballot summary matches its pinned publication.')
    else:
        args.output.write_text(text);print('Wrote '+str(args.output))
