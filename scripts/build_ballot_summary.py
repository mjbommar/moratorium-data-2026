#!/usr/bin/env python3
"""Build a dated public view of reviewed current result observations, not a census."""
import argparse
from collections import Counter
import json
from pathlib import Path

from check_expanded_publication import check
from expanded_data import validate, certified_result_count
from expanded_promotion import ROOT, require


def cell(value):
    if value is None:
        return 'unknown'
    return str(value).replace('|',r'\|').replace('\n',' ')


def citation(source):
    return source.get('citation_url') or source['url']


def render(rows, snapshot):
    results=list(rows['measure_results'].values())
    superseded={r['supersedes_id'] for r in results if r['supersedes_id']}
    live=[r for r in results if r['result_observation_id'] not in superseded]
    lifecycles = Counter(m['lifecycle'] for m in rows['ballot_measures'].values())
    unknown_sector_count = sum(not m['sectors'] for m in rows['ballot_measures'].values())
    sector_notes = []
    if unknown_sector_count:
        noun = 'measure' if unknown_sector_count == 1 else 'measures'
        sector_notes = [f'Sector attribution remains unresolved for {unknown_sector_count} {noun}; '
                        'these records are included in the overall measure count.', '']
    lines=['<!-- Generated by scripts/build_ballot_summary.py; do not edit by hand. -->',
           '# Ballot measures and results','',
           f"**{len(rows['ballot_measures'])} measures and proposals · {len(live)} current result reports · "
           f"{certified_result_count(rows)} certified result reports.**",'',
           'The tracker includes measures with recorded votes, scheduled questions, and proposals with unresolved status. This is not a complete list of elections.','',
           '| Stage | Records |', '|---|---:|',
           *[f'| {dict(voted="Voted", scheduled="Scheduled", litigated="In litigation", unknown="Unknown").get(status, status.replace("_", " ").capitalize())} | {count} |' for status, count in sorted(lifecycles.items())], '',
           'Each table row is the latest result report for a measure and reporting area. A measure may have reports from more than one area. Unknown vote categories are left unknown rather than filled with zero.','',
           *sector_notes,
           'Some reports cover an entire jurisdiction; others cover only a named area. We keep them separate and do not add them together. If the area is unknown, we leave it unknown.','',
           'The effect of a yes vote depends on the question. An advisory question records voter opinion; it does not by itself enact a restriction or approve a project.','',
           '| Measure | Election | Area covered | Binding or advisory | Effect of a yes vote | Yes | No | Blank | Ballots cast | Certification | Reported outcome |',
           '|---|---|---|---|---|---:|---:|---:|---:|---|---|']
    def order(result):
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        return jurisdiction['state'],jurisdiction['name'],result['observed_at'],result['result_observation_id']
    for result in sorted(live,key=order):
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        election=rows['elections'][measure['election_id']]
        source=rows['source_documents'][result['source_document_id']]
        title=jurisdiction['name']+', '+jurisdiction['state']+' — '+(measure['designation'] or measure['title'] or 'undesignated')
        label=f"[{title}](<{citation(source)}>)"
        date=election['election_date']['earliest'] if election['election_date']['precision']=='day' else (election['election_date']['original_text'] or 'unknown')
        cert=result['certification_status']+((' '+result['certification_date']) if result['certification_date'] else '')
        scope=result.get('reporting_scope')
        scope_label=({'jurisdiction_total':'Whole jurisdiction', 'jurisdiction_part':'Partial jurisdiction',
                      'unknown':'Unknown scope'}[scope['kind']]+': '+scope['description']) if scope else 'scope not recorded'
        values=[label,date,scope_label,measure['bindingness'],measure['yes_direction'].replace('_',' '),result['yes_votes'],result['no_votes'],result.get('blank_votes'),result['ballots_cast'],cert,result['reported_outcome']]
        lines.append('| '+' | '.join(cell(v) for v in values)+' |')
    source_notes=[]
    for result in sorted(live,key=order):
        categories=result.get('source_vote_categories',[])
        totals=result.get('source_vote_totals',[])
        if not categories and not totals:continue
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        source=rows['source_documents'][result['source_document_id']]
        notes=[cell(x['label'])+': '+str(x['count'])+' (unmapped category)' for x in categories]
        notes += [cell(x['label'])+': '+str(x['count'])+' ('+cell(x['scope'])+')' for x in totals]
        title=jurisdiction['name']+', '+jurisdiction['state']+' — '+(measure['designation'] or measure['title'] or 'undesignated')
        source_notes.append('- ['+cell(title)+'](<'+citation(source)+'>): '+'; '.join(notes)+'.')
    if source_notes:
        lines += ['', 'The sources also report the following totals. We keep these labels separate because they do not necessarily count the same votes or ballots.']+source_notes
    accounting_notes=[]
    for result in sorted(live,key=order):
        for claim in sorted(rows['claims'].values(),key=lambda c:c['claim_id']):
            if (claim['subject']!={'table':'measure_results','id':result['result_observation_id']}
                    or claim['predicate']!='derived_accounting_discrepancy'):
                continue
            value=claim['value']
            if not isinstance(value,dict) or not {'unreconciled_ballots','formula','classification'} <= set(value):
                continue
            measure=rows['ballot_measures'][result['measure_id']]
            jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
            source=rows['source_documents'][claim['source_document_id']]
            title=jurisdiction['name']+', '+jurisdiction['state']+' — '+(measure['designation'] or measure['title'] or 'undesignated')
            accounting_notes.append('- ['+cell(title)+'](<'+citation(source)+'>): source accounting difference '+
                                    cell(value['unreconciled_ballots'])+'; '+cell(value['formula'])+'. '+
                                    cell(value['classification'])+'.')
    if accounting_notes:
        lines += ['', 'The following source totals do not reconcile. We retain the reported values and leave missing vote categories unknown.']+accounting_notes
    no_results=set(rows['ballot_measures'])-{r['measure_id'] for r in live}
    if no_results:
        noun='measure has' if len(no_results)==1 else 'measures have'
        lines += ['',f'{len(no_results)} {noun} no current result report. A missing result does not show that a measure failed or reached the ballot.']
        lines += ['', '| Measure | Election date (held or proposed) | Stage | Details and limits |', '|---|---|---|---|']
        for mid in sorted(no_results):
            measure=rows['ballot_measures'][mid]
            jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
            election=rows['elections'][measure['election_id']]
            title=jurisdiction['name']+', '+jurisdiction['state']+' — '+(measure['designation'] or measure['title'] or 'undesignated')
            supporting=sorted((c for c in rows['claims'].values()
                               if c['subject']=={'table':'ballot_measures','id':mid}
                               and c['source_document_id'] in rows['source_documents']),
                              key=lambda c:c['claim_id'])
            label=(f"[{title}](<{citation(rows['source_documents'][supporting[0]['source_document_id']])}>)"
                   if supporting else title)
            date=election['election_date']['earliest'] if election['election_date']['precision']=='day' else (election['election_date']['original_text'] or 'unknown')
            lines.append('| '+' | '.join(cell(v) for v in [label,date,measure['lifecycle'].replace('_',' '),measure.get('scope_note')])+' |')
    links = rows.get('measure_instrument_links', {})
    if links:
        lines += ['', '## Linked restriction records', '',
                  'Relationship acceptance is separate from instrument status. A `proposes` link '
                  'does not establish enactment or current force; unknown dates remain unknown.', '',
                  '| Measure | Relationship | Link review | Restriction | Recorded status | Adoption | Effective |',
                  '|---|---|---|---|---|---|---|']
        def date_label(bounds):
            if bounds.get('precision') == 'day' and bounds.get('earliest') == bounds.get('latest'):
                return bounds.get('earliest') or 'unknown'
            return bounds.get('original_text') or 'unknown'
        for link in sorted(links.values(), key=lambda row: row['link_id']):
            if link['instrument']['kind'] != 'restriction':
                continue
            restriction = rows['local_restrictions'][link['instrument']['id']]
            measure = rows['ballot_measures'][link['measure_id']]
            jurisdiction = rows['jurisdictions'][measure['jurisdiction_id']]
            label = jurisdiction['name'] + ', ' + jurisdiction['state'] + ' — ' + (measure['designation'] or measure['title'] or 'undesignated')
            title = restriction['title'] or 'untitled'
            if link['claim_ids']:
                claim = rows['claims'][link['claim_ids'][0]]
                title = '[' + title + '](<' + citation(rows['source_documents'][claim['source_document_id']]) + '>)'
            lines.append('| ' + ' | '.join(cell(value) for value in [label, link['relation'],
                link['review_status'], title, restriction['status'], date_label(restriction['adoption']),
                date_label(restriction['effective'])]) + ' |')
    lines += ['', 'A reported outcome and a certified result do not by themselves establish when a restriction took effect. '
              'Approval does not automatically add a local moratorium to the inventory. '
              'See [scope and interpretation](ballot-measures.md) for questions about legal effect.','',
              f'The data keeps {len(results)} result versions, including earlier reports. '
              'This page shows the latest reports. A correction to a report does not mean new votes were counted or the source was checked again. Source dates and the value_methods notes explain those changes.','',
              '## Sources for reported outcomes','']
    for result in sorted(live,key=order):
        measure=rows['ballot_measures'][result['measure_id']]
        jurisdiction=rows['jurisdictions'][measure['jurisdiction_id']]
        sources={citation(rows['source_documents'][rows['claims'][cid]['source_document_id']])
                 for cid in result.get('value_methods',{}).get('reported_outcome',{}).get('claim_ids',[])}
        if sources:
            lines.append('- '+cell(jurisdiction['name'])+': '+', '.join('[reported-outcome source](<'+url+'>)' for url in sorted(sources))+'.')
    lines += ['',f'Data version: `{snapshot}`. Each record keeps its source and review dates. '
              'Rebuilding this page does not mean each source or legal outcome was checked again.','',
              f'[Canonical publication protocol](expanded-promotion.md) · [Raw reviewed tables](../data/expanded-snapshots/{snapshot}/ballot_measures.jsonl)','']
    return '\n'.join(lines)


def build(directory, registry):
    checked=check(directory,registry,ROOT/'data/moratorium_inventory.csv',ROOT/'data/state_legislation.csv')
    pinned=directory.resolve(strict=True)
    require(pinned.name==checked['snapshot_sha256'],'Publication changed during summary build; rerun against one generation')
    profile=json.loads((pinned/'publication.json').read_text())['plan'].get('validation_profile',{}).get('name','1.0.0')
    errors,rows=validate(pinned,ROOT/'data/moratorium_inventory.csv',ROOT/'data/state_legislation.csv',profile=profile)
    require(not errors,'Invalid published data: '+'; '.join(errors))
    return render(rows,pinned.name)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output',type=Path,default=ROOT/'docs/ballot-results.md')
    args=parser.parse_args();text=build(ROOT/'data/expanded',ROOT/'data/identities/expanded.jsonl')
    if args.check:
        require(args.output.exists() and args.output.read_text()==text,'Ballot summary is stale; run scripts/build_ballot_summary.py')
        print('Reviewed ballot summary matches its pinned publication.')
    else:
        args.output.write_text(text);print('Wrote '+str(args.output))
