"""Generate latex/tables/moratorium-inventory-clean.tex from the inventory CSV.

This is the curated longtable that appears in Appendix A. We emit one row
per canonical inventory record, sorted by state then jurisdiction. Date uses the normalized date and uncertainty fields, duration is normalized via _common.normalize_duration,
sector is the union of detected sectors, instrument form is heuristically
inferred from legal_basis, and status is the recorded enacted_status.

The hand-curated annotations (per-row footnotes about specific bills) are
NOT preserved here — they live in `latex/tables/inventory-annotations.tex`
if needed and are conditionally inputted from this longtable. For now we
keep this generator vanilla; targeted annotations can be reapplied as
sed-style overlays after generation.
"""

from __future__ import annotations

import re
from datetime import date

from ._common import (
    TABLES_DIR,
    classify_all_sectors,
    latex_escape,
    load_inventory,
    normalize_duration,
)


def infer_form(row) -> str:
    """Heuristically classify the instrument form from legal_basis."""
    s = (row.legal_basis or "").lower()
    if "ordinance" in s:
        return "Ordinance"
    if "resolution" in s:
        return "Resolution"
    if "regulation" in s or "land use code" in s or "zoning" in s:
        return "Regulation"
    if "bill" in s or "act" in s or "hb" in s or "sb" in s:
        return "Bill"
    if "motion" in s:
        return "Motion"
    return "Other"


def infer_status(row) -> str:
    """Display the recorded classification, or leave an unknown value blank."""
    return latex_escape(row.enacted_status.replace("_", " ").capitalize())


def short_date(row) -> str:
    """Render only validated canonical dates, preserving uncertainty."""
    value = row.date_enacted_iso
    uncertainty = row.date_enacted_uncertainty
    if uncertainty == "range":
        return "Range"
    if uncertainty not in {"exact", "month_only", "year_only", "range", "unverified"}:
        return ""
    if not re.fullmatch(r"\d{4}(?:-\d{2}(?:-\d{2})?)?", value):
        return ""
    parts = value.split("-")
    try:
        date(int(parts[0]), int(parts[1]) if len(parts) > 1 else 1,
             int(parts[2]) if len(parts) > 2 else 1)
    except ValueError:
        return ""
    if (uncertainty == "exact" and len(parts) != 3 or
        uncertainty == "month_only" and len(parts) != 2 or
        uncertainty == "year_only" and len(parts) != 1):
        return ""
    # The table deliberately displays at most month precision.
    displayed = "-".join(parts[:2])
    return displayed + ("?" if uncertainty in {"unverified", "range"} else "")


def render() -> str:
    rows = sorted(load_inventory(), key=lambda r: (r.state_abbrev, r.jurisdiction.lower()))

    # Group by state for the section comments
    state_chunks: dict[str, list] = {}
    for r in rows:
        state_chunks.setdefault(r.state, []).append(r)
    body = []
    last_state = None
    for r in rows:
        if r.state != last_state:
            body.append(f"%% {r.state}")
            last_state = r.state
        sectors = classify_all_sectors(r)
        sector_str = ", ".join(sectors[:3])
        body.append(
            " & ".join([
                latex_escape(r.jurisdiction),
                r.state_abbrev,
                short_date(r),
                normalize_duration(r.duration),
                latex_escape(sector_str),
                infer_form(r),
                infer_status(r),
            ]) + " \\\\"
        )

    body_text = "\n".join(body)

    return f"""% Auto-generated by scripts/generate_tables/inventory_clean.py
% Source: data/moratorium_inventory.csv
% Snapshot date: README.md, headline numbers (November 5, 2026).
% Population: all canonical inventory records, including aggregate and compound rows; sort by state abbreviation and jurisdiction.
{{\\footnotesize
\\setlength{{\\tabcolsep}}{{3pt}}
\\renewcommand{{\\arraystretch}}{{1.15}}
\\begin{{longtable}}{{p{{0.20\\linewidth}}p{{0.04\\linewidth}}p{{0.12\\linewidth}}p{{0.16\\linewidth}}p{{0.13\\linewidth}}p{{0.105\\linewidth}}p{{0.115\\linewidth}}}}
\\caption{{Local Moratorium Inventory Records (working snapshot, November 5, 2026)}} \\label{{tab:moratorium-inventory}} \\\\
\\toprule
Jurisdiction & ST & Date & Duration & Sector & Form & Status \\\\
\\midrule
\\endfirsthead
\\multicolumn{{7}}{{c}}{{\\tablename\\ \\thetable{{}} -- continued}} \\\\
\\toprule
Jurisdiction & ST & Date & Duration & Sector & Form & Status \\\\
\\midrule
\\endhead
\\noalign{{\\vskip 2pt}}
\\multicolumn{{7}}{{r}}{{\\textit{{Continued on next page}}}} \\\\
\\endfoot
\\bottomrule
\\multicolumn{{7}}{{p{{0.98\\linewidth}}}}{{\\footnotesize\\textit{{Source:}} Author's compilation from municipal records, state legislation, and public documents.}} \\\\
\\multicolumn{{7}}{{p{{0.98\\linewidth}}}}{{\\footnotesize Record-level source and status dates vary; classifications are recorded, not uniformly current.}} \\\\
\\multicolumn{{7}}{{p{{0.98\\linewidth}}}}{{\\footnotesize Dates: year/month precision; ? means unverified; Range means unresolved interval; blank means unknown.}} \\\\
\\multicolumn{{7}}{{p{{0.98\\linewidth}}}}{{\\footnotesize Source: data/moratorium\\_inventory.csv; all canonical rows, including proposals and unresolved aggregate/compound/duplicate identities.}} \\\\
\\multicolumn{{7}}{{p{{0.98\\linewidth}}}}{{\\footnotesize Recorded status does not establish current legal force. Sector (first three) and Form are heuristic; Duration is abbreviated. Consult the CSV and codebook.}} \\\\
\\endlastfoot
{body_text}
\\end{{longtable}}
}}
"""


def main():
    out = TABLES_DIR / "moratorium-inventory-clean.tex"
    out.write_text(render())
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
