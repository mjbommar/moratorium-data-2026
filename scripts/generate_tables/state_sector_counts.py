"""Generate latex/tables/state-sector-counts.tex from the moratorium inventory.

Cross-tab of states (with three or more records) by sector. The input is
data/moratorium_inventory.csv filtered by cleaned_inventory to governmental
rows. Each retained record contributes to each sector in its recorded array.
The Total column counts each retained record once.
"""

from __future__ import annotations

from collections import Counter, defaultdict

from ._common import (
    SECTORS,
    TABLES_DIR,
    cleaned_inventory,
    load_inventory,
)
from .inventory_clean import recorded_sectors

# Always render in this order
COLS = ["Data Center", "Crypto", "BESS", "Solar", "Wind", "Other"]


def render(min_total: int = 3) -> str:
    rows = cleaned_inventory(load_inventory())

    # state -> sector -> count
    matrix: dict[str, Counter] = defaultdict(Counter)
    state_totals: Counter = Counter()
    for r in rows:
        if not r.state:
            continue
        sectors = recorded_sectors(r)
        if "Unknown" in sectors:
            raise ValueError(f"Missing or invalid recorded sectors: {r.state}, {r.jurisdiction}")
        for s in sectors:
            matrix[r.state][s] += 1
        state_totals[r.state] += 1

    qualified = [(s, t) for s, t in state_totals.most_common() if t >= min_total]
    if not qualified:
        raise SystemExit("No states meet the minimum-total threshold")

    body_lines = []
    subtotal = Counter()
    subtotal_total = 0
    for state, total in qualified:
        cells = []
        for col in COLS:
            cells.append(str(matrix[state].get(col, 0)))
            subtotal[col] += matrix[state].get(col, 0)
        body_lines.append(
            f"{state:<14} & " + " & ".join(f"{c:>2}" for c in cells)
            + f" & {total:>2} \\\\"
        )
        subtotal_total += total

    n_qualified = len(qualified)
    remaining_states = len([s for s, t in state_totals.items() if t < min_total])
    remaining_count = sum(t for s, t in state_totals.items() if t < min_total)

    subtotal_cells = " & ".join(f"\\textit{{{subtotal[c]}}}" for c in COLS)
    subtotal_line = (
        f"\\textit{{Subtotal ({n_qualified} states)}} & "
        f"{subtotal_cells} & \\textit{{{subtotal_total}}} \\\\"
    )

    body = "\n".join(body_lines)

    return f"""% Auto-generated by scripts/generate_tables/state_sector_counts.py
% Source: data/moratorium_inventory.csv
\\begin{{table}}[tp]
\\centering
\\caption{{Moratorium Count by State and Sector (States with Three or More)}}
\\label{{tab:state-sector-counts}}
\\begin{{tabular}}{{lrrrrrr r}}
\\toprule
State & Data Ctr. & Crypto & BESS & Solar & Wind & Other & Total \\\\
\\midrule
{body}
\\midrule
{subtotal_line}
\\bottomrule
\\end{{tabular}}
\\begin{{flushleft}}
\\small\\textit{{Note:}} Sector columns count records with each recorded sector label
in the cleaned inventory (\\Cref{{app:inventory}}, $n = {len(rows)}$).
A record may contribute to each sector it covers; state totals count each
record once rather than summing sector columns.
Recorded labels do not independently establish legal scope or current force.
``Other'' includes general industrial moratoria.
The remaining {remaining_states} states ({remaining_count} records) each contribute one or two entries.
\\end{{flushleft}}
\\end{{table}}
"""


def main():
    out = TABLES_DIR / "state-sector-counts.tex"
    out.write_text(render())
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
